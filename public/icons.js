const cache = new Map();
export function icon(name, cls = "ic") {
  const key = name + "|" + cls;
  if (cache.has(key)) return cache.get(key);
  const rows = BITMAPS[name] || BITMAPS.more,
    h = rows.length,
    w = Math.max(...rows.map((r) => r.length));
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let n = 1;
        while (row[x + n] === "#") n++;
        d += `M${x} ${y}h${n}v1h-${n}z`;
        x += n;
      } else x++;
    }
  });
  const svg = `<svg class="${cls}" viewBox="-1 -1 ${w + 2} ${h + 2}" aria-hidden="true" focusable="false" shape-rendering="crispEdges"><path d="${d}" fill="currentColor"/></svg>`;
  cache.set(key, svg);
  return svg;
}
