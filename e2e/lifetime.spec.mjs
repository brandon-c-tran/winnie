import { goTimeline, goPhotos } from './helpers.mjs';
import { test, expect } from '@playwright/test';
import { code, join } from './helpers.mjs';
import { datedPhoto } from './photo-fixture.mjs';

test('original EXIF dates survive a mixed batch, reload, metadata edit and trip collection',async({page},info)=>{
  const errors=await join(page,code(info));
  await goPhotos(page);await page.locator('#story-add').click();
  await page.locator('[data-album-library]').click();
  await page.locator('#library-input').setInputFiles([datedPhoto('2025:12:24 23:30:00'),datedPhoto('2026:01:02 10:20:00')]);
  await expect(page.locator('#photo-draft img')).toHaveCount(2);
  await expect(page.locator('[data-photo-field="wall"]').nth(0)).toHaveValue('2025-12-24T23:30');
  await expect(page.locator('[data-photo-field="wall"]').nth(1)).toHaveValue('2026-01-02T10:20');
  await page.locator('#photo-composer [name="note"]').fill('Texas photos');
  await page.locator('#photo-composer [type="submit"]').click();
  await expect(page.locator('#dialog')).not.toBeVisible();
  await expect(page.locator('#photo-count')).toHaveText('2 photos');
  await expect(page.locator('.photo-month')).toHaveText(['January 2026','December 2025']);
  await expect(page.locator('#sync-status')).toHaveText('Up to date');
  await page.reload();await goPhotos(page);
  await expect(page.locator('#photo-count')).toHaveText('2 photos');
  await page.locator('.memory-card').first().click();await page.locator('[data-edit-photo-meta]').click();
  await page.locator('#photo-metadata-form [name="location"]').fill('Garland');
  await page.locator('#photo-metadata-form [name="zone"]').fill('America/Chicago');
  await page.locator('#photo-metadata-form [type="submit"], #photo-metadata-form button.primary').click();
  await page.locator('#dialog-close').click();
  await page.locator('[data-filter="memories"]').click();
  await page.locator('.album-collections > summary').click();
  await page.locator('[data-new-trip]').click();
  await page.locator('#life-form [name="title"]').fill('Texas Christmas');
  await page.locator('#life-form [name="start"]').fill('2025-12-22');
  await page.locator('#life-form [name="end"]').fill('2026-01-05');
  await page.locator('#life-form .primary').click();
  await expect(page.locator('.life-timeline [data-trip]')).toContainText('Texas Christmas');
  await expect(page.locator('.album-collections [data-trip]')).toContainText('Texas Christmas');
  await page.locator('.life-timeline [data-trip]').click();await expect(page.locator('#dialog .chapter-photos img')).toHaveCount(2);
  await page.locator('#dialog-close').click();
  await page.locator('[data-filter="places"]').click();
  await page.locator('.travel-outing',{hasText:'Texas Christmas'}).click();
  await expect(page.locator('.travel-selected .travel-photos img')).toHaveCount(2);
  await page.getByRole('button',{name:'Next recorded day',exact:true}).click();
  await expect(page.locator('.travel-replay')).toContainText('Dec 24, 2025');
  await expect(page.locator('.travel-selected')).toContainText('No saved location for this day');
  await expect(page.locator('.travel-marker')).toHaveCount(0);
  await expect(page.locator('.travel-selected .travel-photos img')).toHaveCount(1);
  expect(errors).toEqual([]);
});
